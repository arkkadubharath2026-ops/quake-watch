"""Generate docs/AQL_QUERIES.md from the named-query catalog with live EXPLAIN plans."""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from typing import Any

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError, CommandParser

from apps.core.arango import catalog
from apps.core.arango import schema as s
from apps.core.arango.client import get_db, sync
from apps.core.arango.query import explain, indexes_used, run_query
from apps.core.clock import now_iso

HEADER = """# AQL Query Catalogue

Generated by `manage.py aql_catalog --write` from the named-query registry
(`apps/core/arango/catalog.py`) with live `EXPLAIN` plans — do not edit by hand.

- Database: `{db}` · events: {events} · revisions: {revisions} · generated {generated}
- Every query uses bind variables; the explorer search builder composes only allow-listed
  fragments, so the *variants* below are representative compositions of the same builder.
- "Indexes used" is what the optimizer actually chose; "expected" lists the acceptable
  candidates checked by `tests/integration/test_api.py::TestQueryCatalog`.

## Index justification (ESD §6)

| Index | Collection | Used by |
|---|---|---|
{index_rows}

## Queries ({count})

"""


EMPTY_DATABASE_WARNING = (
    "WARNING: the events collection is empty. Index choices are only meaningful on a populated "
    "database (the optimizer has no selectivity statistics here); a BAD result below is not "
    "evidence of a query defect. Run against populated data or rely on TestQueryCatalog."
)


def _index_table(results: list[dict[str, Any]]) -> str:
    usage: dict[str, list[str]] = {}
    for result in results:
        for name in result["indexes"]:
            usage.setdefault(name, []).append(result["query"].name)
    rows = []
    for spec in s.COLLECTIONS:
        for index in spec.indexes:
            users = usage.get(index.name, [])
            if users:
                note = ", ".join(f"`{u}`" for u in users)
            elif index.unique:
                note = "_uniqueness constraint (identity / idempotency)_"
            elif index.type == "ttl":
                note = "_TTL expiry of raw payloads (ADR-007)_"
            else:
                note = "_not exercised by a catalogued query yet_"
            rows.append(f"| `{index.name}` ({index.type}) | `{spec.name}` | {note} |")
    edge_users = usage.get("edge", [])
    if edge_users:
        rows.append(
            "| edge index (built-in) | edge collections | "
            + ", ".join(f"`{u}`" for u in edge_users)
            + " |"
        )
    return "\n".join(rows)


class Command(BaseCommand):
    help = "EXPLAIN every registered AQL query; optionally write docs/AQL_QUERIES.md."

    def add_arguments(self, parser: CommandParser) -> None:
        parser.add_argument("--write", action="store_true", help="write docs/AQL_QUERIES.md")

    def handle(self, *args: Any, **options: Any) -> None:
        db = get_db()
        # Plan choice depends on index selectivity statistics; on empty collections every
        # candidate looks equally selective, so the optimizer may pick another valid index.
        empty = sync(db.collection(s.EVENTS).count()) == 0
        if empty:
            self.stderr.write(EMPTY_DATABASE_WARNING)
        results: list[dict[str, Any]] = []
        failures = []
        for query in catalog.all_queries():
            binds = query.sample_binds()
            plan = explain(db, query.aql, binds)
            used = sorted(set(indexes_used(plan)))
            timing = (
                run_query(db, query.name, query.aql, binds, record_metrics=False)
                if query.read_only
                else None  # write queries are explained, never executed
            )
            ok = query.plan_ok(used)
            if not ok:
                failures.append(query.name)
            results.append(
                {
                    "query": query,
                    "indexes": used,
                    "ok": ok,
                    "cost": plan.get("estimatedCost"),
                    "nodes": Counter(n["type"] for n in plan.get("nodes", [])),
                    "ms": timing.duration_ms if timing else None,
                    "rows": len(timing.rows) if timing else None,
                }
            )
            flag = "ok " if ok else "BAD"
            measured = f"{timing.duration_ms:8.1f} ms" if timing else " explain-only"
            self.stdout.write(f"{flag} {query.name:44s} {measured}  indexes={used}")

        if options["write"]:
            self._write(db, results)
        if failures:
            hint = (
                " (the events collection is empty: re-run on a populated database)" if empty else ""
            )
            raise CommandError(f"queries not using an expected index: {failures}{hint}")

    def _write(self, db: Any, results: list[dict[str, Any]]) -> None:
        lines = [
            HEADER.format(
                db=db.name,
                events=sync(db.collection(s.EVENTS).count()),
                revisions=sync(db.collection(s.EVENT_REVISIONS).count()),
                generated=now_iso(),
                index_rows=_index_table(results),
                count=len(results),
            )
        ]
        category = None
        for number, result in enumerate(results, start=1):
            query = result["query"]
            if query.category != category:
                category = query.category
                lines.append(f"### {category.title()}\n")
            nodes = ", ".join(f"{k} x{v}" if v > 1 else k for k, v in result["nodes"].items())
            lines += [
                f"#### {number}. `{query.name}`\n",
                f"**Question:** {query.question}\n",
                f"- Features: {', '.join(query.features) or '—'}",
                f"- Indexes used: {', '.join(f'`{i}`' for i in result['indexes']) or 'none'}"
                + (
                    f" (expected one of: {', '.join(query.expected_indexes)})"
                    if query.expected_indexes
                    else ""
                ),
                f"- Plan: {nodes}; estimated cost {result['cost']:.0f}"
                if isinstance(result["cost"], int | float)
                else f"- Plan: {nodes}",
                (
                    f"- Measured: {result['ms']:.1f} ms, {result['rows']} row(s) (sample binds)"
                    if result["ms"] is not None
                    else "- Write query: explained only (never executed by tooling)"
                ),
                "",
                "```aql",
                "\n".join(line.rstrip() for line in query.aql.strip("\n").splitlines()),
                "```",
                "",
                "<details><summary>Sample bind variables</summary>\n",
                "```json",
                json.dumps(query.sample_binds(), indent=2, default=str)[:1500],
                "```\n</details>\n",
            ]
        target = Path(settings.BASE_DIR) / "docs" / "AQL_QUERIES.md"
        target.write_text("\n".join(lines), encoding="utf-8", newline="\n")  # LF on Windows too
        self.stdout.write(self.style.SUCCESS(f"wrote {target}"))
